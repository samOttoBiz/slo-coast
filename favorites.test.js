'use strict';
const assert=require('node:assert/strict');
const s=require('./favorites-store.js');
const draft={name:'First cove',notes:'<img src=x onerror=alert(1)>',photo:null};
let list=s.saveEntry([],draft);const first=list[0];
assert.equal(first.notes,draft.notes);assert.equal(first.version,1);
list=s.saveEntry(list,{name:'Second beach',notes:'Two',photo:null});
assert.deepEqual(s.moveEntry(list,list[1].id,-1).map(e=>e.name),['Second beach','First cove']);
assert.deepEqual(s.moveEntry(list,first.id,-1),list);
list=s.saveEntry(list,{...draft,notes:'Updated'},first.id,1);
assert.equal(list[0].notes,'Updated');assert.equal(list[0].version,2);
assert.throws(()=>s.saveEntry(list,draft,first.id,1),/changed in another tab/);
assert.throws(()=>s.saveEntry(list,draft,'missing',1),/removed in another tab/);
assert.throws(()=>s.saveEntry(list,{...draft,name:' FIRST COVE '}),/already/);
assert.throws(()=>s.cleanDraft({...draft,name:' '}),/place name/);
assert.throws(()=>s.cleanDraft({...draft,notes:'a'.repeat(3001)}),/3,000/);
assert.throws(()=>s.cleanDraft({...draft,photo:new Blob(['<svg>'],{type:'image/svg+xml'})}),/supported photo/);
assert.equal(s.photoSignature(Uint8Array.from([255,216,255]),'image/jpeg'),true);
assert.equal(s.photoSignature(Uint8Array.from([137,80,78,71,13,10,26,10]),'image/png'),true);
assert.equal(s.photoSignature(new Uint8Array(12),'image/png'),false);
assert.equal(s.photoSignature(new TextEncoder().encode('RIFF1234WEBP'),'image/webp'),true);
assert.match(s.errorMessage({name:'QuotaExceededError'}),/storage is full/);
const full=Array.from({length:100},(_,i)=>({...first,id:String(i),name:'Place '+i}));
assert.throws(()=>s.saveEntry(full,{...draft,name:'Extra'}),/100 places/);
const large=new Blob([new Uint8Array(2*1024*1024)],{type:'image/jpeg'});
assert.throws(()=>s.saveEntry(Array.from({length:15},(_,i)=>({...first,id:String(i),name:'Photo '+i,photo:large})),{name:'Extra',notes:'',photo:large}),/30 MB/);
console.log('PASS: Favorites validation, literal text, ordering, edit conflicts, duplicate protection, photo signatures and storage limits.');
